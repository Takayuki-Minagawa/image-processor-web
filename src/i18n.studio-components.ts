export const formatStudioMessage = (
  template: string,
  values: Readonly<Record<string, string | number>>,
): string =>
  template.replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g, (placeholder, key) =>
    Object.hasOwn(values, key) ? String(values[key]) : placeholder,
  )
